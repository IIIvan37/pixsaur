/**
 * Get blue noise threshold for a pixel position
 * @param x - X coordinate
 * @param y - Y coordinate
 * @returns Threshold value [0, 1]
 */
export function getBlueNoiseThreshold(x: number, y: number): number {
  const tx = x % BLUE_NOISE_SIZE
  const ty = y % BLUE_NOISE_SIZE
  const value = BLUE_NOISE_64[ty * BLUE_NOISE_SIZE + tx]
  // Clamp to valid range in case of any out-of-bounds values
  return Math.min(255, Math.max(0, value)) / 255
}

/**
 * Get blue noise threshold centered around 0
 * @param x - X coordinate
 * @param y - Y coordinate
 * @returns Threshold value [-0.5, 0.5]
 */
export function getBlueNoiseThresholdCentered(x: number, y: number): number {
  return getBlueNoiseThreshold(x, y) - 0.5
}
